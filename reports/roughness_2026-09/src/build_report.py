def tables(A, P, runs, stems, sp, surf, cal):
    tk = A["tk"]
    v = D.wind(sp)

    lines = []
    for r, spec in enumerate(D.ORDER):
        s, su = D.SPECIMENS[spec], surf[spec]
        thick = "none" if s["fuzz_mm"] == 0 else f"{s['fuzz_mm']:.3f}"
        if r == 0:
            chg = "reference"
        else:
            c = tk["pairs"][(0, r)]
            chg = f"${pct(c['level'])}$ ${ci(c['lo'], c['hi'])}$"
        lines.append(" & ".join([s["label"], thick, f"{su['Pa']:.1f}", f"{su['Ra']:.1f}", chg,
                                 f"{A['curve'][r][-1]:.2f}"]) + r" \\")
    write(TAB / "headline.tex", "\n".join(lines) + "\n")

    lines = []
    for a in range(4):
        for b in range(a + 1, 4):
            c, cf = tk["pairs"][(a, b)], A["tk_fit"]["pairs"][(a, b)]
            lines.append(" & ".join([
                f"{label(D.ORDER[b])} vs {label(D.ORDER[a])}",
                f"${pct(c['level'])}$", f"${ci(c['lo'], c['hi'])}$", f"$p{pval(c['p'])}$",
                f"${pct(cf['level'])}$ ${ci(cf['lo'], cf['hi'])}$"]) + r" \\")
    write(TAB / "pairs.tex", "\n".join(lines) + "\n")

    an = A["anova"]
    names = dict(R="Rotor", S="Set point (wind speed)", RS="Rotor $\\times$ set point",
                 J="Run within rotor", E="Residual")
    against = dict(R="run within rotor", S="", RS="residual", J="residual", E="")
    lines = []
    for k in ("R", "S", "RS", "J", "E"):
        r = an[k]
        show = "F" in r and k != "S"                             # nobody doubts the set-point effect
        lines.append(" & ".join([names[k], str(r["df"]), sig3(1e4 * r["ms"]),
                                 sig3(r["F"]) if show else "", f"$p{pval(r['p'])}$" if show else "",
                                 against[k]]) + r" \\")
    write(TAB / "anova.tex", "\n".join(lines) + "\n")

    lines = []
    for r, spec in enumerate(D.ORDER):
        if r == 0:
            cells = [label(spec)] + ["reference"] * 3
        else:
            cells = [label(spec)]
            for c in (A["tk_voc"]["pairs"][(0, r)], A["tk_rint"]["pairs"][(0, r)], A["spd"]["tk"]["pairs"][(0, r)]):
                cells.append(f"${pct(c['level'])}$ ${ci(c['lo'], c['hi'])}$")
        cells += [f"{100 * A['cp'][r][-1]:.2f}", f"{A['spd']['lam_curve'][r][-1]:.2f}"]
        lines.append(" & ".join(cells) + r" \\")
    write(TAB / "rotor.tex", "\n".join(lines) + "\n")

    lines = []
    for r, spec in enumerate(D.ORDER):
        for j, k in enumerate(stems[spec]):
            a, b = D.times(runs[k])
            lines.append(" & ".join([label(spec) if j == 0 else "", str(j + 1), f"{a}–{b}",
                                     f"${pct(math.expm1(A['yrj'][r, j]))}$",
                                     "\\texttt{" + k.replace("_", "\\_") + "}"]) + r" \\")
    write(TAB / "session.tex", "\n".join(lines) + "\n")

    head = ("Fan & $v$ & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{label(s)}}}" for s in D.ORDER)
            + r" \\" + "\n"
            + "".join(f"\\cmidrule(lr){{{3 + 2 * i}-{4 + 2 * i}}}" for i in range(4)) + "\n"
            + "rpm & m/s & " + " & ".join("1 & 2" for _ in D.ORDER) + r" \\" + "\n")
    pk = lambda r, j, i: P[stems[D.ORDER[r]][j]].set_index("fan_rpm_cmd").p_max_w[sp[i]]
    for name, value in (("data", lambda r, j, i: f"{pk(r, j, i):.4f}"),
                        ("speed", lambda r, j, i: (f"({A['spd']['n_all'][r, j, i]:.0f})" if i == 0
                                                   else f"{A['spd']['n_all'][r, j, i]:.0f}"))):
        body = []
        for i, (s_, vv) in enumerate(zip(sp, v)):
            cells = [str(s_), f"{vv:.1f}"] + [value(r, j, i) for r in range(len(D.ORDER)) for j in range(2)]
            body.append(" & ".join(cells) + r" \\")
        write(TAB / f"{name}.tex", "\\begin{tabular}{@{}rr" + " rr" * 4 + "@{}}\n\\toprule\n" + head
              + "\\midrule\n" + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n")

    lines = []
    for _, r in cal.iterrows():
        fit = float(D.wind(r.rpm))
        lines.append(" & ".join([str(int(r.rpm)), f"{r.velocity:.2f}",
                                 "measured" if r.source == "measured" else "trend line?",
                                 neg(f"{fit:.2f}"), neg(f"{fit - r.velocity:+.2f}")]) + r" \\")
    write(TAB / "calibration.tex", "\n".join(lines) + "\n")


