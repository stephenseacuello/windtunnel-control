def derived(A, P, T, S, runs, stems, sp, surf, t_start_h):
    v = D.wind(sp)
    sa = A["spd"]

    def tagged(frames, k, spec, j):
        f = frames[k].copy()
        f.insert(0, "run", j + 1)
        f.insert(0, "run_name", k)
        f.insert(0, "fuzzy_skin_mm", D.SPECIMENS[spec]["fuzz_mm"])
        f.insert(0, "rotor", label(spec))
        return f

    pk = pd.concat([tagged(P, k, s, j) for s in D.ORDER for j, k in enumerate(stems[s])])
    pk = pk.drop(columns=["logged_p_max_w", "logged_p_fit_w", "last_frac", "fan_rpm_logged"])
    pk.to_csv(DER / "peak_power_by_run.csv", index=False, float_format="%.6g")
    th = pd.concat([tagged(T, k, s, j) for s in D.ORDER for j, k in enumerate(stems[s])])
    th.to_csv(DER / "thevenin_by_run.csv", index=False, float_format="%.6g")
    rs = []
    for r, spec in enumerate(D.ORDER):
        for j, k in enumerate(stems[spec]):
            f = tagged(S, k, spec, j)
            f.insert(f.columns.get_loc("fan_rpm_cmd") + 1, "wind_mps", D.wind(f.fan_rpm_cmd.values))
            f["light_load"] = (f.fan_rpm_cmd > sp[0]).astype(int)   # first set point settles under load
            f["tip_speed_ratio"] = sa["lam_all"][r, j]
            p1 = P[k].set_index("fan_rpm_cmd").reindex(sp)
            f["v_first_v"], f["i_first_a"] = p1.v_first_v.values, p1.i_first_a.values
            f["v_first_per_rpm_mv"] = 1000 * sa["v1_all"][r, j] / sa["n_all"][r, j]
            rs.append(f)
    pd.concat(rs).to_csv(DER / "rotor_speed_by_run.csv", index=False, float_format="%.6g")

    rows = []
    for r, spec in enumerate(D.ORDER):
        for j, k in enumerate(stems[spec]):
            a, b = D.times(runs[k])
            rows.append(dict(rotor=label(spec), fuzzy_skin_mm=D.SPECIMENS[spec]["fuzz_mm"], run=j + 1,
                             run_name=k, first_dwell=a, last_dwell=b, start_h=t_start_h[r, j],
                             p_max_change_vs_plain_pct=100 * math.expm1(A["yrj"][r, j]),
                             v_oc_change_vs_plain_pct=100 * math.expm1(A["voc_rj"][r, j]),
                             r_int_change_vs_plain_pct=100 * math.expm1(A["rint_rj"][r, j]),
                             rotor_rpm_change_vs_plain_pct=100 * math.expm1(sa["yrj"][r, j]),
                             steepest_rise_mps=A["step_v"][r, j]))
    pd.DataFrame(rows).to_csv(DER / "run_summary.csv", index=False, float_format="%.5g")

    rows = []
    for (a, b), c in A["tk"]["pairs"].items():
        if a < b:
            cf, cs = A["tk_fit"]["pairs"][(a, b)], sa["tk"]["pairs"][(a, b)]
            cv, cr = A["tk_voc"]["pairs"][(a, b)], A["tk_rint"]["pairs"][(a, b)]
            rows.append(dict(rotor=label(D.ORDER[b]), relative_to=label(D.ORDER[a]),
                             change_pct=100 * c["level"], tukey95_lo_pct=100 * c["lo"],
                             tukey95_hi_pct=100 * c["hi"], p_tukey=c["p"],
                             fit_change_pct=100 * cf["level"], fit_tukey95_lo_pct=100 * cf["lo"],
                             fit_tukey95_hi_pct=100 * cf["hi"], p_tukey_fit=cf["p"],
                             tipping_point_mounting_sd_pct=100 * A["tau"][(a, b)] if c["resolved"] else np.nan,
                             v_oc_change_pct=100 * cv["level"], v_oc_tukey95_lo_pct=100 * cv["lo"],
                             v_oc_tukey95_hi_pct=100 * cv["hi"],
                             r_int_change_pct=100 * cr["level"], r_int_tukey95_lo_pct=100 * cr["lo"],
                             r_int_tukey95_hi_pct=100 * cr["hi"],
                             rotor_rpm_change_pct=100 * cs["level"], rotor_rpm_tukey95_lo_pct=100 * cs["lo"],
                             rotor_rpm_tukey95_hi_pct=100 * cs["hi"], p_tukey_rotor_rpm=cs["p"]))
    pd.DataFrame(rows).to_csv(DER / "comparisons.csv", index=False, float_format="%.5g")

    dm = A["drift"]
    rows = [dict(term="drift per hour", estimate_pct=100 * dm["beta"], ci95_lo_pct=100 * dm["beta_lo"],
                 ci95_hi_pct=100 * dm["beta_hi"], dof=dm["dof"])]
    for b, c in dm["change"].items():
        rows.append(dict(term=f"{label(D.ORDER[b])} vs Plain, drift-adjusted", estimate_pct=100 * c["level"],
                         ci95_lo_pct=100 * c["lo"], ci95_hi_pct=100 * c["hi"], dof=dm["dof"]))
    pd.DataFrame(rows).to_csv(DER / "drift_model.csv", index=False, float_format="%.5g")

    rows = []
    trim = f"without {' and '.join(map(str, A['trim_dropped']))} rpm"
    src = dict(R="rotor", S="set point", RS="rotor x set point", J="run within rotor", E="residual")
    for name, an in (("ln P_max, all rotors", A["anova"]), ("ln P_max, textured rotors only", A["anova_tex"]),
                     (f"ln P_max, {trim}", A["anova_trim"]), ("ln R_int, all rotors", A["anova_rint"]),
                     ("ln V_oc, all rotors", A["anova_voc"]),
                     (f"ln n_0 (light-load rotor speed), all rotors, {sa['sp'][0]}-{sa['sp'][-1]} rpm",
                      sa["anova"])):
        for k in ("R", "S", "RS", "J", "E"):
            r = an[k]
            rows.append(dict(analysis=name, source=src[k], df=r["df"], ss=r["ss"], ms=r["ms"],
                             F=r.get("F"), df_den=r.get("df_den"), p=r.get("p")))
    pd.DataFrame(rows).to_csv(DER / "anova.csv", index=False, float_format="%.6g")

    rows = []
    for r, spec in enumerate(D.ORDER):
        for i, s_ in enumerate(sp):
            row = dict(rotor=label(spec), fan_rpm_cmd=s_, wind_mps=float(v[i]),
                       p_max_geomean_w=A["curve"][r, i], cp_el=A["cp"][r, i],
                       v_oc_geomean_v=A["voc_curve"][r, i], r_int_geomean_ohm=A["rint_curve"][r, i],
                       rotor_rpm_geomean=sa["curve"][r, i - 1] if i else np.nan,
                       tip_speed_ratio=sa["lam_curve"][r, i - 1] if i else np.nan)
            if r:
                row.update(p_max_change_vs_plain_pct=100 * A["gain"][r, i],
                           run1_change_pct=100 * A["gain_run"][r, 0, i],
                           run2_change_pct=100 * A["gain_run"][r, 1, i],
                           pointwise95_halfwidth_pct=100 * math.expm1(A["band_hw"][i]),
                           v_oc_change_vs_plain_pct=100 * A["voc_gain"][r, i],
                           r_int_change_vs_plain_pct=100 * A["rint_gain"][r, i],
                           rotor_rpm_change_vs_plain_pct=100 * sa["gain"][r, i - 1] if i else np.nan)
            rows.append(row)
    pd.DataFrame(rows).to_csv(DER / "rotor_by_wind_speed.csv", index=False, float_format="%.6g")

    pd.DataFrame([dict(rotor=label(spec), fuzzy_skin_mm=D.SPECIMENS[spec]["fuzz_mm"], scans=s["n_scans"],
                       columns=sum(sc["n_columns"] for sc in s["scans"]), profiles=s["n_profiles"],
                       Pa_um=s["Pa"], Ra_lc025_um=s["Ra"],
                       layer_period_um=np.nan if spec == "v1_Ra80" else s["pitch_um"],
                       Pa_scan_spread_um=s["Pa_spread"], Ra_scan_spread_um=s["Ra_spread"])
                  for spec, s in surf.items()]).to_csv(DER / "surface_roughness.csv", index=False, float_format="%.4g")


